#!/usr/bin/env python3
"""Turns a picasso .shbin into a C header (u32 array, as DVLB_ParseFile wants).

The generated header is committed so that building the 3DS binary needs
nothing beyond devkitARM + libctru + citro3d. Regenerate after editing the
shader:

    picasso -o world.shbin platform/3ds/world.v.pica
    python3 scripts/shbin2h.py world.shbin platform/3ds/world_shbin.h world_shbin

and likewise world_plain.v.pica -> world_plain_shbin.h (world_plain_shbin),
the fallback shader without characters, and world_fade.v.pica -> world_fade_shbin.h.

The default shader is six source files assembled into one binary (six DVLEs
sharing one code blob; the order of the files is the order of the entries:
main, fastmain, fadefast, skinmain, fastsun, fadefastsun - gfx_c3d.cpp takes them by number):

    picasso -o world_fast.shbin platform/3ds/world_full.v.pica platform/3ds/world_fast.v.pica \
        platform/3ds/world_fastfade.v.pica platform/3ds/world_skin.v.pica \
        platform/3ds/world_fastsun.v.pica platform/3ds/world_fastfadesun.v.pica
    python3 scripts/shbin2h.py world_fast.shbin platform/3ds/world_fast_shbin.h world_fast_shbin
"""
import struct
import sys


def main() -> int:
    if len(sys.argv) != 4:
        print(__doc__)
        return 2
    src, dst, name = sys.argv[1:]
    data = open(src, "rb").read()
    if data[:4] != b"DVLB":
        print(f"{src}: not a DVLB shader binary")
        return 1
    data += b"\0" * (-len(data) % 4)
    words = struct.unpack(f"<{len(data) // 4}I", data)
    lines = [
        f"// Generated by scripts/shbin2h.py from {src.split('/')[-1]}; do not edit.",
        "#pragma once",
        f"static unsigned int {name}[] = {{",
    ]
    for i in range(0, len(words), 6):
        lines.append("\t" + " ".join(f"0x{w:08x}," for w in words[i:i + 6]))
    lines += ["};", f"static const unsigned int {name}_size = {len(data)};", ""]
    open(dst, "w").write("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
