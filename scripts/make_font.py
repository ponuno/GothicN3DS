#!/usr/bin/env python3
"""Makes engine/ui_font.h: the bitmap font of the menus and the HUD.

The glyphs are rasterised from DejaVu Sans (Bitstream Vera licence: free to
use, embed and redistribute; see third_party/README.md) in two sizes - the
text and the headings - with Latin, Cyrillic and a few signs, and packed into
one 256x256 atlas of 4-bit coverage. Nothing of the game is in it.

    python3 scripts/make_font.py [path to DejaVuSans.ttf] [path to DejaVuSans-Bold.ttf]
"""
import sys
from PIL import Image, ImageDraw, ImageFont

REG = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
BOLD = sys.argv[2] if len(sys.argv) > 2 else "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
W, H = 256, 256

chars = [chr(c) for c in range(32, 127)]
chars += [chr(c) for c in range(0x410, 0x450)] + ["Ё", "ё"]
chars += list("«»—–…№°←→↑↓×•▶◀▼▲")

sizes = [("text", REG, 11, 13), ("title", BOLD, 15, 18)]

atlas = Image.new("L", (W, H), 0)
glyphs = []  # (size index, codepoint, x, y, w, h, xoff, yoff, advance)
x, y, rowH = 1, 1, 0
metrics = []
for si, (name, path, px, line) in enumerate(sizes):
    font = ImageFont.truetype(path, px)
    ascent, descent = font.getmetrics()
    metrics.append((line, ascent))
    for ch in chars:
        bbox = font.getbbox(ch)  # relative to the pen at the top of the line (ascent above the baseline)
        adv = int(round(font.getlength(ch)))
        if ch == " " or bbox[2] <= bbox[0]:
            glyphs.append((si, ord(ch), 0, 0, 0, 0, 0, 0, adv))
            continue
        gw, gh = bbox[2] - bbox[0], bbox[3] - bbox[1]
        if x + gw + 1 > W:
            x, y, rowH = 1, y + rowH + 1, 0
        if y + gh + 1 > H:
            sys.exit("atlas full")
        img = Image.new("L", (gw, gh), 0)
        ImageDraw.Draw(img).text((-bbox[0], -bbox[1]), ch, font=font, fill=255)
        # A little more ink: thin strokes at 11 px get lost on the console's screen.
        img = img.point(lambda v: min(255, int(v * 1.25)))
        atlas.paste(img, (x, y))
        glyphs.append((si, ord(ch), x, y, gw, gh, bbox[0], bbox[1], adv))
        x += gw + 1
        rowH = max(rowH, gh)

# A solid block for filled rectangles (panels, bars).
atlas.paste(255, (W - 8, H - 8, W, H))

px = atlas.load()
packed = bytearray()
for yy in range(H):
    for xx in range(0, W, 2):
        a = (px[xx, yy] + 8) // 17
        b = (px[xx + 1, yy] + 8) // 17
        packed.append(min(a, 15) | (min(b, 15) << 4))

out = []
out.append("// Generated by scripts/make_font.py from DejaVu Sans (Bitstream Vera licence,")
out.append("// see third_party/README.md). Do not edit.")
out.append("#pragma once")
out.append('#include "g3ds/base.h"')
out.append("")
out.append("namespace g3 {")
out.append("namespace uifont {")
out.append("")
out.append(f"constexpr int ATLAS_W = {W}, ATLAS_H = {H};")
out.append(f"constexpr int SIZES = {len(sizes)};")
out.append("// A solid 8x8 block of the atlas: rectangles are drawn with its middle.")
out.append(f"constexpr int SOLID_X = {W - 4}, SOLID_Y = {H - 4};")
out.append("// Per size: the height of a line and how far the baseline is below its top.")
out.append("constexpr int LINE[SIZES] = {" + ", ".join(str(m[0]) for m in metrics) + "};")
out.append("constexpr int ASCENT[SIZES] = {" + ", ".join(str(m[1]) for m in metrics) + "};")
out.append("")
out.append("struct Glyph {")
out.append("\tu16 code;")
out.append("\tu8 size;")
out.append("\tu8 x, y, w, h; // in the atlas")
out.append("\ti8 left, top;  // from the pen at the top of the line")
out.append("\tu8 advance;")
out.append("};")
out.append(f"constexpr int GLYPHS = {len(glyphs)};")
out.append("// In order of size, then code: found by bisection.")
glyphs.sort(key=lambda g: (g[0], g[1]))
out.append("static const Glyph kGlyphs[GLYPHS] = {")
for g in glyphs:
    si, code, gx, gy, gw, gh, xo, yo, adv = g
    out.append(f"    {{{code}, {si}, {gx}, {gy}, {gw}, {gh}, {xo}, {yo}, {adv}}},")
out.append("};")
out.append("")
out.append("// 4-bit coverage, two texels a byte (the left one in the low nibble), rows from the top.")
out.append(f"static const u8 kAtlas[{len(packed)}] = {{")
for i in range(0, len(packed), 24):
    out.append("    " + ", ".join(str(b) for b in packed[i:i + 24]) + ",")
out.append("};")
out.append("")
out.append("} // namespace uifont")
out.append("} // namespace g3")
open("engine/ui_font.h", "w").write("\n".join(out) + "\n")
print(f"{len(glyphs)} glyphs, atlas used to row {y + rowH} of {H}")
